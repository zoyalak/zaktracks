export type Sex = 'male' | 'female' | 'undisclosed'
export type ActivityKey = 'sedentary' | 'light' | 'moderate' | 'active' | 'very_active'
export type GoalType = 'maintain' | 'cut' | 'bulk'
export type UnitSystem = 'metric' | 'imperial'
export type MealSource = 'photo' | 'describe' | 'food' | 'manual'

export interface Profile {
  sex: Sex
  age: number
  heightCm: number
  weightKg: number
  activity: ActivityKey
  goal: GoalType
  /** Weight the user wants to reach. Equal to weightKg when maintaining. */
  targetWeightKg: number
  /** Weeks over which the target weight should be reached. */
  weeks: number
  /** Grams of protein per kg of reference body weight. */
  proteinPerKg: number
  /** Percentage of daily calories that come from fat. Set automatically from
   *  the goal via defaultSplit — deliberately not user-facing. */
  fatPct: number
  units: UnitSystem
  /** Daily macro goals chosen by the AI for this profile, when generated. */
  aiTargets?: AiTargets
}

export interface Macro {
  kcal: number
  protein: number
  carbs: number
  fat: number
}

/**
 * The macros beyond protein/carbs/fat. All values are per portion (LogItem) or
 * per 100 g / serving (Food). Units are grams except sodium/potassium/calcium/
 * iron, which are milligrams.
 */
export interface ExtraMacros {
  fiber: number
  sugar: number
  saturatedFat: number
  sodium: number
  potassium: number
  calcium: number
  iron: number
}

export const EXTRA_KEYS = [
  'fiber',
  'sugar',
  'saturatedFat',
  'sodium',
  'potassium',
  'calcium',
  'iron',
] as const

export type ExtraKey = (typeof EXTRA_KEYS)[number]

export const EXTRA_META: Record<ExtraKey, { label: string; unit: string }> = {
  fiber: { label: 'Fiber', unit: 'g' },
  sugar: { label: 'Sugar', unit: 'g' },
  saturatedFat: { label: 'Sat fat', unit: 'g' },
  sodium: { label: 'Sodium', unit: 'mg' },
  potassium: { label: 'Potassium', unit: 'mg' },
  calcium: { label: 'Calcium', unit: 'mg' },
  iron: { label: 'Iron', unit: 'mg' },
}

export const emptyExtras = (): ExtraMacros => ({
  fiber: 0,
  sugar: 0,
  saturatedFat: 0,
  sodium: 0,
  potassium: 0,
  calcium: 0,
  iron: 0,
})

const t1 = (n: number): number => Math.round(n * 10) / 10

export const addExtras = (a: ExtraMacros, b?: Partial<ExtraMacros> | null): ExtraMacros => ({
  fiber: t1(a.fiber + (b?.fiber ?? 0)),
  sugar: t1(a.sugar + (b?.sugar ?? 0)),
  saturatedFat: t1(a.saturatedFat + (b?.saturatedFat ?? 0)),
  sodium: Math.round(a.sodium + (b?.sodium ?? 0)),
  potassium: Math.round(a.potassium + (b?.potassium ?? 0)),
  calcium: Math.round(a.calcium + (b?.calcium ?? 0)),
  iron: t1(a.iron + (b?.iron ?? 0)),
})

/** True when any extra value is non-zero — used to skip empty sections. */
export const hasExtras = (e?: Partial<ExtraMacros> | null): boolean =>
  Boolean(e && EXTRA_KEYS.some((k) => (e[k] ?? 0) > 0))

/** Daily targets for the extra macros, as chosen by the AI for the user. */
export type ExtraTargets = Partial<ExtraMacros>

/** Daily macro goals generated by the AI from the user's profile. */
export interface AiTargets {
  protein: number
  carbs: number
  fat: number
  extras: ExtraTargets
  rationale?: string
  model?: string
  at?: number
}

export interface LogItem {
  name: string
  /** Grams (or ml) this portion represents, when known. */
  grams: number | null
  kcal: number
  protein: number
  carbs: number
  fat: number
  /** Extended macros for this portion, when known (from AI or a label). */
  extras?: ExtraMacros
  foodId?: string
}

export interface MealEntry {
  id: string
  /** Local date key, YYYY-MM-DD. */
  date: string
  /** 24h local time, HH:MM. */
  time: string
  name: string
  note: string
  /** Data URL of the meal photo, when one was taken. */
  photo?: string
  source: MealSource
  items: LogItem[]
  createdAt: number
}

export interface Food {
  id: string
  name: string
  brand?: string
  per: '100g' | 'serving'
  /** Human label for a serving, e.g. "1 cup (240 ml)". */
  servingLabel?: string
  /** Grams in one serving, when per === 'serving'. */
  gramsPerServing?: number
  kcal: number
  protein: number
  carbs: number
  fat: number
  /** Extended macros per 100 g / serving, when known (from a label scan). */
  extras?: ExtraMacros
  source: 'builtin' | 'label' | 'manual' | 'recipe'
  /**
   * For a recipe (source === 'recipe'): one entry per ingredient, macros for
   * the amount given. The fields above hold the totals for the whole batch.
   */
  ingredients?: LogItem[]
  category?: string
  createdAt?: number
}

export interface WeightPoint {
  date: string
  kg: number
}

export interface Settings {
  weightLog: WeightPoint[]
}

export interface AppData {
  profile: Profile | null
  meals: MealEntry[]
  foods: Food[]
  settings: Settings
}

export const emptyMacro = (): Macro => ({ kcal: 0, protein: 0, carbs: 0, fat: 0 })

export const addMacro = (a: Macro, b: Macro): Macro => ({
  kcal: a.kcal + b.kcal,
  protein: a.protein + b.protein,
  carbs: a.carbs + b.carbs,
  fat: a.fat + b.fat,
})

export const roundMacro = (m: Macro): Macro => ({
  kcal: Math.round(m.kcal),
  protein: Math.round(m.protein),
  carbs: Math.round(m.carbs),
  fat: Math.round(m.fat),
})

export const itemToMacro = (i: LogItem): Macro => ({
  kcal: i.kcal,
  protein: i.protein,
  carbs: i.carbs,
  fat: i.fat,
})

/** Sum the extended macros across a meal's items. */
export const itemsToExtras = (items: LogItem[]): ExtraMacros =>
  items.reduce<ExtraMacros>((acc, i) => addExtras(acc, i.extras), emptyExtras())

export const mealToExtras = (m: MealEntry): ExtraMacros => itemsToExtras(m.items)

/** Scale a food's per-100 g extras down to a portion; undefined when empty. */
export const scaleExtras = (
  e: Partial<ExtraMacros> | null | undefined,
  factor: number,
): ExtraMacros | undefined => {
  if (!hasExtras(e)) return undefined
  return {
    fiber: Math.round((e?.fiber ?? 0) * factor * 10) / 10,
    sugar: Math.round((e?.sugar ?? 0) * factor * 10) / 10,
    saturatedFat: Math.round((e?.saturatedFat ?? 0) * factor * 10) / 10,
    sodium: Math.round((e?.sodium ?? 0) * factor),
    potassium: Math.round((e?.potassium ?? 0) * factor),
    calcium: Math.round((e?.calcium ?? 0) * factor),
    iron: Math.round((e?.iron ?? 0) * factor * 10) / 10,
  }
}

export const itemsToMacro = (items: LogItem[]): Macro =>
  items.reduce((acc, item) => addMacro(acc, itemToMacro(item)), emptyMacro())

export const mealToMacro = (m: MealEntry): Macro => itemsToMacro(m.items)

/** Sum the grams a list of items represents, ignoring entries with no weight. */
export const itemsToGrams = (items: LogItem[]): number =>
  Math.round(items.reduce((s, i) => s + (i.grams ?? 0), 0) * 10) / 10

/**
 * Scale every item by a portion factor — used when a saved recipe is logged
 * at a different size than the batch it was built from.
 */
export const scaleItems = (items: LogItem[], factor: number): LogItem[] =>
  items.map((i) => ({
    ...i,
    grams: i.grams === null ? null : Math.round(i.grams * factor * 10) / 10,
    kcal: Math.round(i.kcal * factor),
    protein: Math.round(i.protein * factor * 10) / 10,
    carbs: Math.round(i.carbs * factor * 10) / 10,
    fat: Math.round(i.fat * factor * 10) / 10,
    extras: scaleExtras(i.extras, factor),
  }))
